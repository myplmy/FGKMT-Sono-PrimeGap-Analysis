SCHEMA_VERSION = "p012-stratified-hypergeometric-v1"
ANALYSIS_LIMIT = 1_000_000_000
DEFAULT_SEGMENT_SPAN = 50_000_000
DEFAULT_SEED = 20_260_827
DEFAULT_REPLICATIONS = 100_000

def run_stratified_null(
    complete_plateaus_path: Path,
    p011_statistics_path: Path,
    output_directory: Path,
    *,
    approval_token: str | None,
    analysis_limit: int = ANALYSIS_LIMIT,
    segment_span: int = DEFAULT_SEGMENT_SPAN,
    replications: int = DEFAULT_REPLICATIONS,
    seed: int = DEFAULT_SEED,
    make_plots: bool = True,
) -> dict[str, object]:
    require_experiment_approval(approval_token)
    if output_directory.exists():
        raise FileExistsError(f"refusing to overwrite P012 result: {output_directory}")
    started = time.perf_counter()
    analysis = compute_stratified_analysis(
        complete_plateaus_path,
        p011_statistics_path,
        analysis_limit=analysis_limit,
        segment_span=segment_span,
        replications=replications,
        seed=seed,
    )
    output_directory.mkdir(parents=True)
    with (output_directory / "input_complete_plateaus.csv").open("xb") as handle:
        handle.write(complete_plateaus_path.read_bytes())
    with (output_directory / "input_p011_plateau_statistics.csv").open("xb") as handle:
        handle.write(p011_statistics_path.read_bytes())
    _write_json_exclusive(output_directory / "analysis.json", analysis)
    _write_csv_exclusive(
        output_directory / "bin_components.csv",
        _serializable_rows(analysis["components"]),
    )
    _write_csv_exclusive(
        output_directory / "plateau_statistics.csv",
        _serializable_rows(analysis["rows"]),
    )
    _write_json_exclusive(
        output_directory / "cohort_summary.json", {"cohorts": analysis["cohorts"]}
    )
    figure_paths = (
        _plot_comparison(analysis["rows"], output_directory / "figures")
        if make_plots
        else []
    )
    summary = {
        "status": "PASS",
        "experiment": EXPERIMENT,
        "analysis_limit": analysis_limit,
        "modeled_rows": len(analysis["rows"]),
        "component_rows": len(analysis["components"]),
        "replications": replications,
        "base_seed": seed,
        "elapsed_seconds": time.perf_counter() - started,
        "figure_count": len(figure_paths),
        "holdout_touched": False,
        "theorem_claimed": False,
        "gpu_used": False,
    }
    _write_json_exclusive(output_directory / "summary.json", summary)
    artifacts = sorted(path for path in output_directory.rglob("*") if path.is_file())
    manifest = {
        "status": "PASS",
        "experiment": EXPERIMENT,
        "schema_version": SCHEMA_VERSION,
        "input_sha256": {
            "complete_plateaus": COMPLETE_PLATEAUS_SHA256,
            "p011_plateau_statistics": P011_STATISTICS_SHA256,
        },
        "artifacts_sha256": {
            path.relative_to(output_directory).as_posix(): sha256_file(path)
            for path in artifacts
        },
        "replications": replications,
        "base_seed": seed,
        "analysis_limit": analysis_limit,
        "segment_span": segment_span,
        "holdout_touched": False,
        "theorem_claimed": False,
        "gpu_used": False,
    }
    _write_json_exclusive(output_directory / "manifest.json", manifest)
    return summary


def verify_saved_stratified_null(output_directory: Path) -> dict[str, object]:
    issues: list[str] = []
    try:
        manifest = json.loads((output_directory / "manifest.json").read_text("utf-8"))
        saved_analysis = json.loads((output_directory / "analysis.json").read_text("utf-8"))
        artifacts = manifest.get("artifacts_sha256", {})
        if not isinstance(artifacts, dict):
            raise StratifiedNullError("manifest artifact hashes are missing")
        for relative, expected in artifacts.items():
            path = output_directory / str(relative)
            if not path.is_file() or sha256_file(path) != str(expected):
                issues.append(f"artifact missing/hash mismatch: {relative}")
        recomputed = compute_stratified_analysis(
            output_directory / "input_complete_plateaus.csv",
            output_directory / "input_p011_plateau_statistics.csv",
            analysis_limit=int(manifest["analysis_limit"]),
            segment_span=int(manifest["segment_span"]),
            replications=int(manifest["replications"]),
            seed=int(manifest["base_seed"]),
        )
        if recomputed != saved_analysis:
            issues.append("saved analysis differs from deterministic full recomputation")
        if manifest.get("holdout_touched") is not False:
            issues.append("P012-A manifest incorrectly claims holdout access")
    except Exception as exc:
        issues.append(f"saved P012 verification failed: {type(exc).__name__}: {exc}")
    return {
        "status": "PASS" if not issues else "FAIL",
        "issues": issues,
        "deterministic_full_recomputation": "PASS" if not issues else "FAIL",
        "manifest_sha256": (
            hashlib.sha256((output_directory / "manifest.json").read_bytes()).hexdigest()
            if (output_directory / "manifest.json").is_file()
            else None
        ),
        "holdout_touched": False,
        "theorem_claimed": False,
    }



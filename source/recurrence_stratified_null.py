"""P012 log-x stratified conditional recurrence null model.

This module is an empirical diagnostic.  It conditions on the observed count
of each record-gap size inside fixed log10 bins and randomizes only its
positions inside each bin.  It does not assume that prime gaps are stationary,
independent, or generated by this null model.
"""

